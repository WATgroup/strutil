//go:build generate

package main

import (
	"fmt"
	self "github.com/WATgroup/strutil"
	"os"
)

func main() {

	args := os.Args
	if len(args) < 3 {
		fmt.Println("Wrong number of arguments: expected 3, got", len(args))
		os.Exit(1)
	}
	if "--" != args[1] {
		fmt.Println("Expected end-of-options, got", args[1])
	}

	out, err := os.OpenFile(args[2], os.O_RDWR|os.O_CREATE, 0644)
	if nil != err {
		fmt.Println("Couldn't create output file, bailing out")
		os.Exit(2)
	}
	defer out.Close()

	fmt.Fprintln(out, "// SPDX-FileCopyrightText: (C) 2024-2026 W-A-T EU Operations Oü")
	fmt.Fprintln(out, "// SPDX-License-Identifier: EUPL-1.2\n")
	fmt.Fprintln(out, `// Code generated by: "go run -tags generate tablegen.go`, args[1], args[2], `"; DO NOT EDIT.`)
	fmt.Fprintln(out, "\n")
	fmt.Fprintln(out, "package strutil\n")

	genAsciiTable(out, "tab_Alpha", self.IsAsciiAlpha)
	genAsciiTable(out, "tab_Alnum", self.IsAsciiAlnum)

	// fmt.Println("Hello World!")
	os.Exit(0)
}

func genAsciiTable(out *os.File, varname string, pred func(rune) bool) error {

	fmt.Fprintf(out, `var %s = [...]bool{`, varname)

	for c := range 256 {
		if 0 == c % 16 {
			fmt.Fprintf(out, "\n\t")
		}
		var x = false
		if pred(rune(c)) {
			x = true
		}
		fmt.Fprintf(out, "%v,", x)
	}

	fmt.Fprintln(out, "\n}\n")
	return nil
}
